# README.md ไม่ต้องซิงค์ — เขียนที่ repo ไม่มีในโฟลเดอร์รัน


def is_user_data(rel_path):
    """เช็คว่าพาธนี้เป็นของลูกค้าไหม (ใช้กันพลาดตอนใส่ไฟล์เข้า ZIP)"""
    rel = rel_path.replace("\\", "/").lstrip("./")
    top = rel.split("/")[0]
    return rel in USER_DATA_FILES or top in USER_DATA_DIRS
